@pytest.mark.asyncio
async def test_enterprise_search_customers_audit_logging():
    """Verify enterprise search writes a tamper-evident audit record to compliance_immutable_audit_logs."""
    sysadmin_user = User(
        id="user-sysadmin",
        username="superadmin",
        role=UserRole.SYSADMIN,
        is_active=True,
        is_deleted=False,
    )
    tenant = TenantContext(
        company_id="COMP-001",
        branch_id="MAIN",
        role=UserRole.SYSADMIN,
    )
    mock_db = AsyncMock()

    # Mock empty last audit entry for hash-chaining
    mock_last_result = MagicMock()
    mock_last_result.scalars.return_value.first.return_value = None
    mock_db.execute.return_value = mock_last_result

    # Mock customer results
    mock_cust = Customer(
        id="cust-enterprise-01",
        name="Reliance Retail Global",
        code="CUST-REL-01",
        mobile="9820012345",
        email="corp@reliance.com",
        gst_number="27AAACR1234F1Z5",
        company_id="COMP-002",
        branch_id="MAIN",
        status="Active",
        is_active=True,
        is_deleted=False,
    )
    mock_cust.company_relationships = []

    with patch.object(CustomerRepository, "enterprise_search", new=AsyncMock(return_value=[mock_cust])):
        results = await enterprise_search_customers(
            q="Reliance",
            skip=0,
            limit=50,
            status="Active",
            current_user=sysadmin_user,
            db=mock_db,
            tenant_ctx=tenant,
        )

        assert len(results) == 1
        assert results[0].name == "Reliance Retail Global"

        # Verify ComplianceImmutableAuditLog added and committed
        assert mock_db.add.called
        added_obj = mock_db.add.call_args[0][0]
        assert isinstance(added_obj, ComplianceImmutableAuditLog)
        assert added_obj.event_type == "CROSS_COMPANY_LOOKUP"
        assert added_obj.entity_name == "CUSTOMER"
        assert added_obj.entity_id == "Reliance"
        assert added_obj.actor_user_id == "user-sysadmin"
        assert added_obj.actor_role == "SYSADMIN"
        assert added_obj.worm_locked is True
        assert added_obj.retention_policy == "STATUTORY_7_YEARS"
        assert len(added_obj.payload_hash) == 64  # SHA-256 hex digest
        assert mock_db.commit.called
