def test_customer_response_serialization_with_company_relationships():
    """Verify CustomerResponse DTO serializes company_relationships cleanly."""
    now = datetime.now(timezone.utc)
    ccr = CustomerCompanyRelationship(
        id="ccr-101",
        uuid=str(uuid.uuid4()),
        customer_id="cust-001",
        company_id="COMP-002",
        branch_id="MAIN",
        customer_group_id="CG-RETAIL",
        price_tier_id=None,
        credit_limit=Decimal("250000.00"),
        credit_days=30,
        credit_hold=False,
        status="Active",
        is_active=True,
        is_deleted=False,
        created_at=now,
        modified_at=now,
    )

    cust = Customer(
        id="cust-001",
        name="Tata Motors Commercial",
        code="CUST-TATAMOT",
        mobile="9876543210",
        email="contact@tatamotors.com",
        gst_number="27AAACT2727Q1ZW",
        company_id="COMP-001",
        branch_id="BR-MAIN-001",
        status="Active",
        is_active=True,
        is_deleted=False,
        version=1,
    )
    cust.company_relationships = [ccr]

    dto = CustomerResponse.from_orm_customer(cust)
    assert dto is not None
    assert dto.id == "cust-001"
    assert len(dto.company_relationships) == 1
    rel = dto.company_relationships[0]
    assert rel.id == "ccr-101"
    assert rel.company_id == "COMP-002"
    assert rel.credit_limit == Decimal("250000.00")
    assert rel.credit_days == 30
    assert rel.credit_hold is False


def test_customer_repository_model_c_tenant_filter_generation():
    """Verify SQL statement generated by _apply_tenant_filter contains Model C relational exists clause."""
    from sqlalchemy.future import select
    tenant_ctx = TenantContext(
        company_id="COMP-002",
        branch_id="MAIN",
        role=UserRole.MANAGER,
    )
    mock_db = MagicMock()
    repo = CustomerRepository(mock_db, tenant_ctx)

    stmt = select(Customer)
    filtered_stmt = repo._apply_tenant_filter(stmt)
    sql_str = str(filtered_stmt.compile(compile_kwargs={"literal_binds": False}))

    # Verify company filter clauses are in compiled statement
    assert "customers.company_id =" in sql_str or "customers.company_id IS" in sql_str
    assert "customer_company_relationships" in sql_str
    assert "EXISTS" in sql_str


