  let md = `# SDIC Scan Progress Change History\n\n`;
  md += `*Generated: ${res.timestamp}*\n\n`;
  md += `| Timestamp | DHI Score | Implementation Completeness | Quality Rating | Security Rating | Verdict |\n`;
  md += `| :--- | :---: | :---: | :---: | :---: | :--- |\n`;
  
