// 1.6 SCAN_DIFF.md (SDS v2.6 Trend & Drift Engine)
export function generateScanDiffReport(res: ScanResult): string {
  let md = `# SMRITI Architecture Scan Diff & Historical Trend Report (SDS v2.6)\n\n`;
  md += `> **Framework:** SDS v${res.fingerprint?.version || "2.6.0"} | **Scan Timestamp:** ${res.timestamp} | **Prior Baseline:** ${res.scanDiff?.previousTimestamp || "Initial Scan"}\n\n`;

  md += `## 1. Executive Metric Delta Summary\n\n`;
  md += `| Metric | Current Value | Previous Value | Delta |\n`;
  md += `|---|:---:|:---:|:---:|\n`;
  md += `| **Development Health Index (DHI)** | ${res.releaseScores.dhi}% | ${(res.releaseScores.dhi - (res.scanDiff?.dhiDelta || 0))}% | ${res.scanDiff?.dhiDelta ? (res.scanDiff.dhiDelta > 0 ? `+${res.scanDiff.dhiDelta}% 📈` : `${res.scanDiff.dhiDelta}% 📉`) : "0% (Stable)"} |\n`;
  md += `| **Quality Score** | ${res.releaseScores.qualityScore}% | ${(res.releaseScores.qualityScore - (res.scanDiff?.qualityDelta || 0))}% | ${res.scanDiff?.qualityDelta ? (res.scanDiff.qualityDelta > 0 ? `+${res.scanDiff.qualityDelta}% 📈` : `${res.scanDiff.qualityDelta}% 📉`) : "0% (Stable)"} |\n`;
  md += `| **Test Suite Coverage** | ${res.releaseScores.testCoverage}% | ${res.releaseScores.testCoverage}% | 0% (Stable) |\n`;
  md += `| **Documentation Coverage** | ${res.releaseScores.documentation}% | ${res.releaseScores.documentation}% | 0% (Stable) |\n\n`;

  md += `## 2. Historical Execution Trend (Last 5 Scans)\n\n`;
  md += `| Timestamp | DHI Score | Quality | Release Score | Grade |\n`;
  md += `|---|:---:|:---:|:---:|:---:|\n`;

  if (res.history && res.history.length > 0) {
    const recent = res.history.slice(-5).reverse();
    for (const h of recent) {
      let g = "D";
      if (h.dhi >= 90) g = "A";
      else if (h.dhi >= 80) g = "B";
      else if (h.dhi >= 70) g = "C";
      md += `| \`${h.timestamp}\` | ${h.dhi}% | ${h.qualityScore}% | ${h.releaseScore}% | Grade ${g} |\n`;
    }
  } else {
    md += `| \`${res.timestamp}\` | ${res.releaseScores.dhi}% | ${res.releaseScores.qualityScore}% | ${res.releaseScores.releaseScore}% | Grade ${res.releaseScores.grade} |\n`;
  }

  md += `\n---\n*Generated by SMRITI Scan Diff Engine (SDS v2.6) | Timestamp: ${res.timestamp}*\n`;
  return md;
}

